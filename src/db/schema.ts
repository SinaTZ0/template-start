import { boolean, index, integer, pgTable, text, timestamp, uuid } from "drizzle-orm/pg-core";

/*===== Database Schema =====*/
// Single source of truth for tables, read by Drizzle Kit (`drizzle.config.ts`) and the
// runtime client (`client.server.ts`). Every change ships as a migration: `pnpm db:generate --name <what-changed>`, then
// `pnpm db:migrate` (docs/backend/architecture.md, Database).

/*===== Auth (Better-Auth) =====*/
// Mirrors Better-Auth's core tables. Table and column names must match its model and field
// names (`user`, `emailVerified`, …) because the Drizzle adapter looks them up by key, so keep
// them in sync with `@better-auth/core` when upgrading. IDs are strings generated by Better-Auth.

export const user = pgTable("user", {
  id: text("id").primaryKey(),
  name: text("name").notNull(),
  email: text("email").notNull().unique(),
  emailVerified: boolean("email_verified").notNull().default(false),
  image: text("image"),
  // Plain text instead of pg enums: allowed values live in `src/lib/user-constants.ts`. Never set from the client
  // (`input: false` in `auth.server.ts`).
  role: text("role").notNull().default("user"),
  status: text("status").notNull().default("active"),
  createdAt: timestamp("created_at").notNull().defaultNow(),
  updatedAt: timestamp("updated_at")
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date()),
});

export const session = pgTable(
  "session",
  {
    id: text("id").primaryKey(),
    expiresAt: timestamp("expires_at").notNull(),
    token: text("token").notNull().unique(),
    createdAt: timestamp("created_at").notNull().defaultNow(),
    updatedAt: timestamp("updated_at")
      .notNull()
      .$onUpdate(() => new Date()),
    ipAddress: text("ip_address"),
    userAgent: text("user_agent"),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
  },
  (table) => [index("session_user_id_idx").on(table.userId)],
);

export const account = pgTable(
  "account",
  {
    id: text("id").primaryKey(),
    accountId: text("account_id").notNull(),
    providerId: text("provider_id").notNull(),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    accessToken: text("access_token"),
    refreshToken: text("refresh_token"),
    idToken: text("id_token"),
    accessTokenExpiresAt: timestamp("access_token_expires_at"),
    refreshTokenExpiresAt: timestamp("refresh_token_expires_at"),
    scope: text("scope"),
    password: text("password"),
    createdAt: timestamp("created_at").notNull().defaultNow(),
    updatedAt: timestamp("updated_at")
      .notNull()
      .$onUpdate(() => new Date()),
  },
  (table) => [index("account_user_id_idx").on(table.userId)],
);

export const verification = pgTable(
  "verification",
  {
    id: text("id").primaryKey(),
    identifier: text("identifier").notNull(),
    value: text("value").notNull(),
    expiresAt: timestamp("expires_at").notNull(),
    createdAt: timestamp("created_at").notNull().defaultNow(),
    updatedAt: timestamp("updated_at")
      .notNull()
      .defaultNow()
      .$onUpdate(() => new Date()),
  },
  (table) => [index("verification_identifier_idx").on(table.identifier)],
);

/*===== Media =====*/
// One row per uploaded image (docs/backend/media.md). The row's id is the `mediaId` in the storage key, and it is inserted only
// after every variant is in the bucket. Entities point to it with a nullable foreign key (`note.image_media_id`, ...).

export const media = pgTable(
  "media",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    // Plain text instead of a pg enum. Allowed values and their variants live in `src/orpc/media/constants.ts`.
    kind: text("kind").notNull(),
    uploadedBy: text("uploaded_by")
      .notNull()
      .references(() => user.id, { onDelete: "restrict" }),
    /** Of the original after rotation, for the `inside` variants' aspect ratio. */
    width: integer("width").notNull(),
    height: integer("height").notNull(),
    /** Data URI of a 16 px wide WebP, shown blurred while the image loads. */
    placeholder: text("placeholder").notNull(),
    /** Set when an entity starts using it. Null means not used yet; the cleanup deletes it 25 hours after upload. */
    attachedAt: timestamp("attached_at"),
    createdAt: timestamp("created_at").notNull().defaultNow(),
  },
  // Serves the cleanup's "unattached and older than 25 hours" scan (`findOrphanedMediaIds`).
  (table) => [index("media_attached_at_created_at_idx").on(table.attachedAt, table.createdAt)],
);

/*===== Notes (example feature) =====*/
// The template's example of a full feature (`src/orpc/note/`, `src/routes/notes/`). Delete it when starting a project.

export const note = pgTable(
  "note",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    ownerId: text("owner_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    title: text("title").notNull(),
    body: text("body").notNull().default(""),
    /** Cleared if the media row is ever deleted, so a note never points at a missing image. */
    imageMediaId: uuid("image_media_id").references(() => media.id, { onDelete: "set null" }),
    createdAt: timestamp("created_at").notNull().defaultNow(),
  },
  (table) => [index("note_owner_id_created_at_idx").on(table.ownerId, table.createdAt)],
);

/*===== Deploy Steps =====*/
// The server's record of the deploy steps it ran (`deploy/steps/`, docs/deployment.md → Deploy Steps). Only the deploy
// tool reads and writes it, through psql; the app never does. It lives in the database so that a restored dump rolls
// it back with the data the steps changed. The `_baseline` row marks a ledger started: the steps that existed then
// are `skipped`, since a new server's seed already loads what they would.

export const deployStep = pgTable("deploy_step", {
  /** The step file's name without `.md`, or `_baseline`. */
  name: text("name").primaryKey(),
  /** How many commands the step has. */
  commands: integer("commands").notNull(),
  /** How many of them finished; a rerun starts after these. */
  done: integer("done").notNull().default(0),
  /** Marked done without running, when the ledger was started. */
  skipped: boolean("skipped").notNull().default(false),
  startedAt: timestamp("started_at").notNull().defaultNow(),
  /** Null until every command finished. */
  finishedAt: timestamp("finished_at"),
});
